                ],
            ],
        ],
        'Fashion' => [
            'description' => 'Clothing and accessories for everyone.',
            'subcategories' => [
                "Men's Clothing" => [
                    ['Classic Cotton Polo', 1500, 1200],
                    ['Slim Fit Denim Jeans', 2800, 2200],
                ],
                "Women's Clothing" => [
