    public function run(): void
    {
        Storage::disk('public')->makeDirectory(Product::IMAGE_DIR);

        foreach (self::CATALOG as $categoryName => $categoryData) {
            $category = Category::firstOrCreate(
                ['name' => $categoryName],
                ['description' => $categoryData['description'], 'is_active' => true],
            );

            foreach ($categoryData['subcategories'] as $subcategoryName => $products) {
                $subcategory = Subcategory::firstOrCreate(
                    ['category_id' => $category->id, 'name' => $subcategoryName],
                    ['description' => "Browse our range of {$subcategoryName}.", 'is_active' => true],
                );

                foreach ($products as [$productName, $oldPrice, $newPrice]) {
                    if (Product::where('name', $productName)->exists()) {
                        continue;
                    }

                    Product::create([
                        'category_id' => $category->id,
                        'subcategory_id' => $subcategory->id,
                        'name' => $productName,
                        'description' => "{$productName} from our {$subcategoryName} collection. "
                            .'High quality, reliable and backed by our standard warranty. '
                            .'This is demo content generated by the database seeder.',
                        'image' => $this->makeImage($productName),
                        'old_price' => $newPrice === null ? null : $oldPrice,
                        'new_price' => $newPrice ?? $oldPrice,
                        'is_active' => true,
                    ]);
                }
            }
        }
    }

    /** Generate a simple labelled PNG and return its path on the public disk. */
    private function makeImage(string $label): ?string
    {
        if (! function_exists('imagecreatetruecolor')) {
            return null; // GD not available – the UI falls back to a placeholder.
        }

        // Draw on a small canvas and upscale so the built-in GD font is legible.
        $size = 200;
        $img = imagecreatetruecolor($size, $size);

        // Deterministic pastel colour per product name.
        $hash = crc32($label);
        $bg = imagecolorallocate($img, 150 + ($hash & 0x3F), 150 + (($hash >> 6) & 0x3F), 150 + (($hash >> 12) & 0x3F));
        $fg = imagecolorallocate($img, 40, 40, 50);
        imagefill($img, 0, 0, $bg);

        // Centre the label using the built-in font (no TTF dependency).
        $font = 5;
        $lines = explode("\n", wordwrap($label, 18, "\n", true));
        $lineHeight = imagefontheight($font) * 2;
        $y = (int) (($size - count($lines) * $lineHeight) / 2);
        foreach ($lines as $line) {
            $x = (int) (($size - imagefontwidth($font) * strlen($line)) / 2);
            imagestring($img, $font, $x, $y, $line, $fg);
            $y += $lineHeight;
        }

        $scaled = imagescale($img, 600, 600, IMG_NEAREST_NEIGHBOUR);
        imagedestroy($img);

        $path = Product::IMAGE_DIR.'/seed-'.Str::slug($label).'.png';
        ob_start();
        imagepng($scaled);
        Storage::disk('public')->put($path, ob_get_clean());
        imagedestroy($scaled);

        return $path;
    }
}
